export function resolveSealSkillName(name = "") {
  const key = String(name || "").trim()
  return SEAL_SKILL_ALIASES[key] || key
}

// 反向分组：规范名 -> [自身+全部别名]，供读取侧候选键匹配
export const SEAL_ALIAS_GROUPS = (() => {
  const groups = {}
  for (const [alias, canon] of Object.entries(SEAL_SKILL_ALIASES)) {
    groups[canon] ||= [canon]
    if (!groups[canon].includes(alias)) groups[canon].push(alias)
  }
  return groups
})()

/** 读取侧候选键：原名优先，其后规范名与同组别名（写入不归一，读取全覆盖） */
export function sealSkillLookupKeys(name = "") {
  const key = String(name || "").trim()
  const canon = SEAL_SKILL_ALIASES[key] || key
  const group = SEAL_ALIAS_GROUPS[canon] || [canon]
  const keys = [key]
  for (const candidate of group) if (!keys.includes(candidate)) keys.push(candidate)
  return keys
}
